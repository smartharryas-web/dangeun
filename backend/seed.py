with Session(engine) as db:
  # 사용자: 없는 아이디만 만든다 (이미 있는 사용자는 그대로 둔다)
  users = {}
  for username in USERNAMES:
    user = db.scalar(select(User).where(User.username == username))
    if user is None:
      user = User(username=username, password_hash=password_hash.hash(username))
      db.add(user)
    users[username] = user
  db.flush()  # id를 미리 받아 둔다

  # 상품: 다시 실행해도 같은 결과가 되도록 지우고 새로 넣는다 (찜 · 댓글이 상품을 가리키므로 먼저 지운다)
  db.execute(delete(Like))
  db.execute(delete(Comment))
  db.execute(delete(Product))

  for p in PRODUCTS:
    # 사진 여러 장: 'images' 목록이 있으면 그걸, 없으면 옛 모양('image_url' 한 장)을 쓴다
    images = p.get('images') or [p['image_url']]

    product = Product(
      title=p['title'],
      price=p['price'],
      description=p['description'],
      image_url=images[0],  # 대표 사진은 첫 장
      location=p['location'],
      status=p['status'],
      seller_id=users[p['seller']].id,
      created_at=p['created_at'],
      category=p.get('category'),
      condition=p.get('condition'),
      brand=p.get('brand'),
      tags=p.get('tags'),
      negotiable=p.get('negotiable', False),
      can_meet=p.get('can_meet', True),
      can_ship=p.get('can_ship', False),
      shipping_included=p.get('shipping_included', False),
      has_warranty=p.get('has_warranty', False),
      view_count=p.get('view_count', 0),
    )
    for position, url in enumerate(images):
      product.images.append(ProductImage(url=url, position=position))
    db.add(product)

  db.commit()
  print('시드 완료: 사용자', len(USERNAMES), '명, 상품', len(PRODUCTS), '개')
